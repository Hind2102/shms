"""Site geometry from the approved concept map, shared by the site plan, report form, dashboard and routing.

The map is ``shms/static/ata_concept_map.svg`` (1920 × 1080 drawing units, origin top left), generated by
``scripts/site_plan/make_map5.py``. Zones come from its ``<g id="zone-CODE" data-points data-name data-reporting>``
groups and the road network from the lines and perimeter rectangle in ``<g id="roads">``. Concept layout only –
positions are indicative and not a verified plot plan.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from dataclasses import dataclass
from functools import cached_property
from heapq import heappop, heappush

from sqlalchemy import select
from sqlalchemy.orm import Session

from .models import Area, Hazard
from .settings import PACKAGE_DIR

MAP_FILE = PACKAGE_DIR / "static" / "ata_concept_map.svg"
MAP_URL = "/static/ata_concept_map.svg"
VIEW_W, VIEW_H = 1920, 1080
TITLE_STRIP_H = 66  # the drawing's own title strip; hidden in the app, whose page heading already names the site
FOOTER_NOTE = (
    "Concept layout only — roads, equipment and facility positions are indicative and require a verified site "
    "plot plan."
)
GATE = (1458, 1000)  # south gate at the end of the main access road
ADJACENT = 30  # a road centre-line within this distance of a zone serves (and passes beside) that zone

Point = tuple[int, int]
Segment = tuple[Point, Point]


@dataclass(frozen=True)
class Zone:
    code: str
    name: str
    points: tuple[Point, ...]
    reporting: bool

    @cached_property
    def x(self) -> int:
        return min(p[0] for p in self.points)

    @cached_property
    def y(self) -> int:
        return min(p[1] for p in self.points)

    @cached_property
    def w(self) -> int:
        return max(p[0] for p in self.points) - self.x

    @cached_property
    def h(self) -> int:
        return max(p[1] for p in self.points) - self.y

    @property
    def points_attr(self) -> str:
        return " ".join(f"{x},{y}" for x, y in self.points)

    @property
    def centre(self) -> Point:
        return (self.x + self.w // 2, self.y + self.h // 2)

    def edges(self) -> list[Segment]:
        return list(zip(self.points, self.points[1:] + self.points[:1], strict=True))

    def contains(self, px: float, py: float) -> bool:
        """Point in polygon; points on the outline count as inside."""
        if any(_dist_point_segment((px, py), e) < 1e-9 for e in self.edges()):
            return True
        inside = False
        for (x1, y1), (x2, y2) in self.edges():
            if (y1 > py) != (y2 > py) and px < x1 + (py - y1) * (x2 - x1) / (y2 - y1):
                inside = not inside
        return inside

    def distance(self, p: tuple[float, float]) -> float:
        return 0.0 if self.contains(*p) else min(_dist_point_segment(p, e) for e in self.edges())


def _dist_point_segment(p: tuple[float, float], seg: Segment) -> float:
    (x1, y1), (x2, y2) = seg
    dx, dy = x2 - x1, y2 - y1
    t = 0.0 if dx == dy == 0 else max(0.0, min(1.0, ((p[0] - x1) * dx + (p[1] - y1) * dy) / (dx * dx + dy * dy)))
    return ((p[0] - x1 - t * dx) ** 2 + (p[1] - y1 - t * dy) ** 2) ** 0.5


def _num(v: str) -> int:
    return round(float(v))


def _load() -> tuple[tuple[Zone, ...], tuple[Segment, ...]]:
    root = ET.parse(MAP_FILE).getroot()
    ns = {"s": "http://www.w3.org/2000/svg"}
    zones = []
    for g in root.iter("{http://www.w3.org/2000/svg}g"):
        if g.get("id", "").startswith("zone-") and g.get("data-points"):
            pts = tuple(tuple(_num(c) for c in p.split(",")) for p in g.get("data-points").split())
            zones.append(Zone(g.get("data-code"), g.get("data-name"), pts, g.get("data-reporting") == "true"))
    roads = root.find(".//s:g[@id='roads']", ns)
    segments: list[Segment] = []
    for el in roads:
        tag = el.tag.split("}")[1]
        if tag == "line":
            a = (_num(el.get("x1")), _num(el.get("y1")))
            b = (_num(el.get("x2")), _num(el.get("y2")))
            if a != b:
                segments.append((min(a, b), max(a, b)))
        elif tag == "rect":  # perimeter road (rounded corners treated as square: indicative only)
            x0, y0 = _num(el.get("x")), _num(el.get("y"))
            x1, y1 = x0 + _num(el.get("width")), y0 + _num(el.get("height"))
            segments += [((x0, y0), (x1, y0)), ((x0, y1), (x1, y1)), ((x0, y0), (x0, y1)), ((x1, y0), (x1, y1))]
    return tuple(zones), tuple(segments)


ZONES, ROADS = _load()
REPORTING: dict[str, Zone] = {z.code: z for z in ZONES if z.reporting}


def zone(code: str) -> Zone | None:
    return next((z for z in ZONES if z.code == code), None)


def _is_h(seg: Segment) -> bool:
    return seg[0][1] == seg[1][1]


def _on(seg: Segment, p: Point) -> bool:
    (x1, y1), (x2, y2) = seg
    return (y1 == y2 == p[1] and x1 <= p[0] <= x2) or (x1 == x2 == p[0] and y1 <= p[1] <= y2)


def _seg_zone_distance(seg: Segment, z: Zone) -> float:
    """Shortest distance between a road centre-line and a zone outline (0 if they touch)."""
    d = min(_dist_point_segment(c, seg) for c in z.points)
    return min(d, *(_dist_point_segment(end, e) for end in seg for e in z.edges()))


def entrances(z: Zone) -> list[Point]:
    """Where each road beside the zone meets it: the zone centre projected onto that road, kept beside the zone."""
    out = []
    for seg in ROADS:
        if _seg_zone_distance(seg, z) > ADJACENT:
            continue
        (x1, y1), (x2, y2) = seg
        if _is_h(seg):
            p = (max(x1, z.x, min(x2, z.x + z.w, z.centre[0])), y1)
            p = (min(p[0], x2, z.x + z.w), y1)
        else:
            p = (x1, max(y1, z.y, min(y2, z.y + z.h, z.centre[1])))
            p = (x1, min(p[1], y2, z.y + z.h))
        if _on(seg, p) and p not in out:
            out.append(p)
    return out


def _split_points(seg: Segment) -> list[Point]:
    pts = {seg[0], seg[1]}
    for other in ROADS:  # junctions
        for cand in ((other[0][0], seg[0][1]), (seg[0][0], other[0][1])):
            if _on(seg, cand) and _on(other, cand):
                pts.add(cand)
    for z in ZONES:  # zone extents, so every piece of road is either fully beside a zone or not
        for c in (z.x, z.x + z.w) if _is_h(seg) else (z.y, z.y + z.h):
            cand = (c, seg[0][1]) if _is_h(seg) else (seg[0][0], c)
            if _on(seg, cand):
                pts.add(cand)
        pts.update(p for p in entrances(z) if _on(seg, p))
    return sorted(pts)


def road_edges() -> list[Segment]:
    """The road graph: every centre-line split at junctions, zone extents and zone entrances."""
    edges = []
    for seg in ROADS:
        pts = _split_points(seg)
        edges.extend(zip(pts, pts[1:], strict=False))
    return edges


EDGES = road_edges()


def flagged_areas(db: Session) -> set[str]:
    """Areas with an active (open, planned or awaiting verification) High or Extreme hazard, any report date."""
    from .services import ACTIVE

    return set(
        db.scalars(
            select(Area.code)
            .join(Hazard)
            .where(Hazard.status.in_(ACTIVE), Hazard.risk_level.in_(("High", "Extreme")))
            .distinct()
        )
    )


def blocked_edges(flagged: set[str]) -> set[Segment]:
    zones = [z for z in ZONES if z.code in flagged]
    return {
        e
        for e in EDGES
        if any(z.distance(((e[0][0] + e[1][0]) / 2, (e[0][1] + e[1][1]) / 2)) < ADJACENT for z in zones)
    }


def _doorway(z: Zone, entrance: Point) -> Point:
    """The point on the zone outline nearest to its road entrance (end of the drawn route)."""
    return (min(max(entrance[0], z.x), z.x + z.w), min(max(entrance[1], z.y), z.y + z.h))


def _simplify(path: list[Point]) -> list[Point]:
    """Drop repeated points and points in the middle of a straight run (same drawing, shorter markup)."""
    out: list[Point] = []
    for p in path:
        if out and p == out[-1]:
            continue
        if len(out) >= 2 and (out[-2][0] == out[-1][0] == p[0] or out[-2][1] == out[-1][1] == p[1]):
            out[-1] = p
        else:
            out.append(p)
    return out


def walk_route(code: str, flagged: set[str]) -> list[Point]:
    """Shortest road route from the south gate to the destination, avoiding every road beside a zone with active
    High or Extreme hazards. Empty if the destination is unknown, not a reporting zone, flagged or unreachable."""
    dest = REPORTING.get(code)
    if dest is None or code in flagged:
        return []
    targets = set(entrances(dest))
    blocked = blocked_edges(flagged)
    graph: dict[Point, list[Point]] = {}
    for a, b in EDGES:
        if (a, b) not in blocked:
            graph.setdefault(a, []).append(b)
            graph.setdefault(b, []).append(a)
    queue = [(0, GATE)]
    distance = {GATE: 0}
    parent: dict[Point, Point] = {}
    while queue:
        cost, node = heappop(queue)
        if node in targets:
            path = [node]
            while path[-1] != GATE:
                path.append(parent[path[-1]])
            return _simplify([*path[::-1], _doorway(dest, node)])
        if cost != distance[node]:
            continue
        for other in graph.get(node, []):
            new = cost + abs(node[0] - other[0]) + abs(node[1] - other[1])
            if other not in distance or new < distance[other]:
                distance[other] = new
                parent[other] = node
                heappush(queue, (new, other))
    return []
